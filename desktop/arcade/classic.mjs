const ids = Object.keys(CLASSIC_ADAPTERS);

export function validateClassicGame(value) {
  const c = value.classic;
  if (!c || !ids.includes(c.adapter) || Object.keys(c).some(k => !["adapter", "runtime", "core", "engine"].includes(k)) ||
      typeof c.runtime !== "string" || !value.runtimes.includes(c.runtime) ||
      !CLASSIC_ADAPTERS[c.adapter].extension.test(value.entry)) throw new Error("Invalid classic runtime binding or game entry.");
  if (c.adapter === "libretro") {
    if (typeof c.core !== "string" || !value.runtimes.includes(c.core) || c.core === c.runtime || value.runtimes.length !== 2)
      throw new Error("RetroArch needs a separately pinned compatible core.");
  } else if (c.core || value.runtimes.length !== 1) throw new Error("Unexpected classic runtime dependency.");
  if (c.adapter === "scummvm" && !/^[a-z0-9][a-z0-9_-]{0,59}$/.test(c.engine ?? ""))
    throw new Error("Choose an explicit ScummVM engine/game identifier.");
  if (c.adapter !== "scummvm" && c.engine) throw new Error("Engine identifiers apply only to ScummVM.");
  if (c.adapter === "dosbox-staging" && !value.entry.split("/").every(p => /^[a-zA-Z0-9_-]{1,8}(?:\.[a-zA-Z0-9_-]{1,3})?$/.test(p)))
    throw new Error("Select the original DOS 8.3 executable path; automatic long-name aliasing could break game data.");
  if (value.runtimeEntry || value.arguments?.length) throw new Error("Classic launch arguments are generated by the adapter, not imported packages.");
}

export function validateClassicRuntime(value) {
  const r = value.classicRuntime;
  if (!r || ![...ids.filter(x => x !== "libretro"), "retroarch", "gambatte-libretro"].includes(r.adapter) ||
      Object.keys(r).some(k => !["adapter", "entry", "source", "license", "api"].includes(k)) ||
      typeof r.source !== "string" || !/^https:\/\//.test(r.source) || typeof r.license !== "string" || !r.license.trim())
    throw new Error("Invalid independently managed classic runtime metadata.");
  safePackagePath(r.entry);
  if (!value.files.some(f => f.path === r.entry) || !r.entry.toLowerCase().endsWith(r.adapter === "gambatte-libretro" ? ".dll" : ".exe") ||
      (r.adapter === "gambatte-libretro" && r.api !== 1)) throw new Error("Pinned classic executable/core or ABI is missing.");
}

export function classicBinding(descriptor, catalog) {
  validateClassicGame(descriptor);
  const c = descriptor.classic, runtime = catalog.get(c.runtime), core = c.core ? catalog.get(c.core) : undefined;
  const wanted = c.adapter === "libretro" ? "retroarch" : c.adapter;
  if (runtime?.kind !== "runtime" || runtime.classicRuntime?.adapter !== wanted)
    throw new Error(`Install a declared ${wanted} runtime; an unrelated executable is not a compatible engine.`);
  validateClassicRuntime(runtime);
  if (c.core && (core?.kind !== "runtime" || core.classicRuntime?.adapter !== "gambatte-libretro" || core.classicRuntime.api !== 1))
    throw new Error("Select a pinned Gambatte Libretro API 1 core, separately from RetroArch.");
  if (core) validateClassicRuntime(core);
  return { runtime, core };
}

/** Called only after all owned native children have stopped. Never follow
 * attacker-created profile links during owner-side configuration/copying. */
export async function assertClassicProfile(profile, root) {
  if (!path.isAbsolute(profile) || !profile.startsWith(`${root}${path.sep}`)) throw new Error("Classic profile escaped managed storage.");
  const managedRoot = await lstat(root);
  if (!managedRoot.isDirectory() || managedRoot.isSymbolicLink()) throw new Error("Managed profile root is not a regular directory.");
  let ancestor = profile;
  while (ancestor !== root) {
    const s = await lstat(ancestor);
    if (!s.isDirectory() || s.isSymbolicLink()) throw new Error("A classic profile ancestor is not a regular directory.");
    ancestor = path.dirname(ancestor);
  }
  let count = 0;
  const walk = async dir => {
    for (const name of await readdir(dir)) {
      if (++count > 10_000) throw new Error("Classic profile exceeds its entry budget; manage its states before relaunch.");
      const file = path.join(dir, name), info = await lstat(file);
      if (info.isSymbolicLink() || (!info.isDirectory() && (!info.isFile() || info.nlink !== 1)))
        throw new Error("Classic profile contains a link or special file. No owner-side write was attempted.");
      if (info.isDirectory()) await walk(file);
    }
  };
  await walk(profile);
}

async function writeConfig(profile, name, content, { once = false, backup = true, limit = 1024 * 1024 } = {}) {
  const target = path.join(profile, name);
  let previous;
  try {
    const info = await lstat(target);
    if (!info.isFile() || info.nlink !== 1 || info.size > limit) throw new Error("Classic configuration/input is not a bounded ordinary file.");
    previous = await readFile(target);
    if (once || previous.equals(Buffer.from(content))) return;
  } catch (e) { if (e.code !== "ENOENT") throw e; }
  if (previous && backup) {
    const dir = path.join(profile, "config-backups"); await mkdir(dir, { recursive: true });
    await writeSyncedAtomic(path.join(dir, `${name}.${Date.now()}.${randomUUID()}`), previous);
    const names = (await readdir(dir)).filter(n => n.startsWith(`${name}.`)).sort().reverse();
    for (const old of names.slice(3)) await rm(path.join(dir, old));
  }
  await writeSyncedAtomic(target, content);
}

export async function backupClassicConfiguration(profile, root) {
  await assertClassicProfile(profile, root);
  const names = new Set(["arena-dosbox.conf", "mapper.map", "scummvm.ini", "retroarch.cfg", "arena-retroarch.cfg", "core-options.cfg", "prefs.bin"]);
  const visit = async directory => {
    for (const name of await readdir(directory)) {
      const file = path.join(directory, name), info = await lstat(file);
      if (info.isDirectory()) { if (name !== "config-backups") await visit(file); continue; }
      if (!names.has(name)) continue;
      if (info.size > 1024 * 1024) throw new Error("A native configuration exceeds its backup budget; no runtime binding was changed.");
      const relative = path.relative(profile, file), hash = createHash("sha256").update(relative).digest("hex").slice(0, 12);
      await writeConfig(profile, `before-runtime-${hash}-${name}`, await readFile(file));
    }
  };
  await visit(profile);
}

async function dosWorkingCopy({ descriptor, install, profile, storage }) {
  const files = descriptor.files;
  if (!Array.isArray(files) || !files.length || files.length > 2000) throw new Error("DOS working copy needs a verified source file manifest.");
  const content = createHash("sha256").update(JSON.stringify(files.map(f => [f.path, f.sha256]).sort())).digest("hex");
  // Native children may write anywhere inside profile. Keep authority outside it.
  const origin = path.join(path.dirname(profile), `${path.basename(profile)}.dos-origin.json`);
  const info = await lstat(origin).catch(e => { if (e.code !== "ENOENT") throw e; return null; });
  if (info && (!info.isFile() || info.isSymbolicLink() || info.nlink > 1 || info.size > 1024)) throw new Error("Unsafe DOS profile origin.");
  const old = info ? JSON.parse(await readFile(origin, "utf8")) : null;
  if (old && (old.schemaVersion !== 1 || old.content !== content))
    throw new Error("DOS source content changed. Use a fresh isolated profile; the existing working copy and progress were not overwritten.");
  const copies = [];
  for (const file of files) {
    safePackagePath(file.path);
    const target = path.join(profile, "saves", ...file.path.split("/"));
    const current = await lstat(target).catch(e => { if (e.code !== "ENOENT") throw e; return null; });
    if (!current) copies.push({ file, target });
    else if (!old && await sha256File(target) !== file.sha256) throw new Error("Existing DOS profile data conflicts with the source. It was not overwritten.");
  }
  const bytes = copies.reduce((sum, c) => sum + c.file.bytes, 0), disk = await statfs(profile);
  const buckets = ["downloads", "staging", "installed", "profiles", "build-cache", "workshop"];
  if (storage && buckets.some(k => !Number.isFinite(storage[k]))) throw new Error("Managed storage usage could not be measured; DOS data was not copied.");
  const used = storage ? buckets.reduce((sum, k) => sum + storage[k], 0) : 0;
  if (disk.bavail * disk.bsize < bytes + (storage?.reserveBytes ?? 512 * 1024 ** 2) ||
      (storage && used + bytes > storage.budgetBytes)) throw new Error("Not enough reserved managed space for the DOS working copy. Existing progress is intact.");
  for (const { file, target } of copies) {
    await mkdir(path.dirname(target), { recursive: true });
    const temp = `${target}.${randomUUID()}.tmp`;
    try { await copyFile(path.join(install, ...file.path.split("/")), temp); await rename(temp, target); }
    finally { await rm(temp, { force: true }); }
  }
  if (!old) await writeFile(origin, JSON.stringify({ schemaVersion: 1, content }), { flag: "wx", mode: 0o600 });
}
const quoteConfig = s => {
  if (/["\r\n\0]/.test(s)) throw new Error("A managed path cannot be represented in this runtime configuration.");
  return `"${s.replaceAll("\\", "/")}"`;
};

export async function prepareClassicLaunch({ descriptor, catalog, filename, install, profile, root, storage }) {
  const { runtime: rt, core } = classicBinding(descriptor, catalog), c = descriptor.classic;
  const runtime = filename(c.runtime), executable = path.join(runtime, rt.classicRuntime.entry);
  await assertClassicProfile(profile, root);
  const dirs = ["saves", "states", "system"];
  for (const dir of dirs) await mkdir(path.join(profile, dir), { recursive: true });
  let args;
  if (c.adapter === "dosbox-staging") {
    await dosWorkingCopy({ descriptor, install, profile, storage });
    if ([install, profile].some(s => /[%&|<>"\r\n\0]/.test(s))) throw new Error("DOSBox mounting needs a managed data path without DOS shell metacharacters; existing data was retained.");
    await writeConfig(profile, "arena-dosbox.conf", "[sdl]\nfullscreen=false\nmapperfile=mapper.map\n[dosbox]\nmemsize=32\n[joystick]\njoysticktype=auto\n[mixer]\nnosound=false\n[autoexec]\n");
    args = ["--noprimaryconf", "--nolocalconf", "--conf", path.join(profile, "arena-dosbox.conf"),
      "-c", `mount c ${quoteConfig(path.join(profile, "saves"))} -freesize 64`,
      "-c", `mount d ${quoteConfig(install)} -ro`, "-c", "c:", "-c", "config -securemode",
      "-c", `cd \\${path.posix.dirname(descriptor.entry) === "." ? "" : path.posix.dirname(descriptor.entry).replaceAll("/", "\\")}`,
      "-c", path.posix.basename(descriptor.entry), "-c", "exit"];
  } else if (c.adapter === "scummvm") {
    await writeConfig(profile, "scummvm.ini", "[scummvm]\n", { once: true });
    args = [`--config=${path.join(profile, "scummvm.ini")}`, `--path=${install}`,
      `--savepath=${path.join(profile, "saves")}`, "--gfx-mode=normal", c.engine];
  } else if (c.adapter === "libretro") {
    await writeConfig(profile, "retroarch.cfg", 'config_save_on_exit = "true"\nmenu_driver = "rgui"\nvideo_driver = "gdi"\ninput_joypad_driver = "xinput"\n', { once: true });
    const config = {
      savefile_directory: path.join(profile, "saves"),
      savestate_directory: path.join(profile, "states", createHash("sha256").update(`${c.runtime}:${c.core}`).digest("hex").slice(0, 16)),
      system_directory: path.join(profile, "system"), libretro_directory: filename(c.core),
      core_options_path: path.join(profile, "core-options.cfg"), screenshot_directory: path.join(profile, "states"),
      playlist_directory: path.join(profile, "states"), content_database_path: path.join(profile, "states"),
      network_cmd_enable: "false", stdin_cmd_enable: "false", menu_show_core_updater: "false",
      content_show_netplay: "false", input_auto_game_focus: "1", savestate_auto_load: "false", savestate_auto_save: "false",
    };
    await mkdir(config.savestate_directory, { recursive: true });
    await writeConfig(profile, "arena-retroarch.cfg", Object.entries(config).map(([k, v]) => `${k} = ${quoteConfig(v)}`).join("\n"));
    args = ["--config", path.join(profile, "retroarch.cfg"), "--appendconfig", path.join(profile, "arena-retroarch.cfg"),
      "-L", path.join(filename(c.core), core.classicRuntime.entry), path.join(install, descriptor.entry)];
  } else {
    // SameBoy stores battery/state files alongside the ROM. Stage ONLY the ROM,
    // restoring its verified immutable content before each launch; retain saves.
    const rom = path.join(profile, path.basename(descriptor.entry));
    const source = await readFile(path.join(install, descriptor.entry));
    if (source.length > 8 * 1024 * 1024) throw new Error("Standalone GB/GBC imports are limited to 8 MiB.");
    await writeConfig(profile, path.basename(rom), source, { backup: false, limit: 8 * 1024 * 1024 });
    args = ["--nogl", rom];
  }
  return { executable, args, additionalReadRoots: core ? [filename(c.core)] : [], diagnostics: {
    adapter: c.adapter, runtime: `${rt.id}@${rt.version}`, core: core ? `${core.id}@${core.version}` : null,
    runtimeLicense: rt.classicRuntime.license, coreLicense: core?.classicRuntime.license ?? null,
    controls: CLASSIC_ADAPTERS[c.adapter].controls, saves: CLASSIC_ADAPTERS[c.adapter].saves,
    limitations: CLASSIC_ADAPTERS[c.adapter].limitations, profile,
    recipeHash: createHash("sha256").update(JSON.stringify({ c, args })).digest("hex"),
    gameplayVerified: false, requiredAssets: c.adapter === "scummvm" ? "Owner-authorized engine-specific game data; no restricted assets acquired."
      : c.adapter === "dosbox-staging" ? "Owner-authorized DOS program and associated data; no Windows execution or host-drive mounts."
      : "No proprietary BIOS is acquired or required by the selected GB/GBC adapters.",
  } };
}
